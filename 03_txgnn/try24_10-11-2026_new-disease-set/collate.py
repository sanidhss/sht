# Job C (CPU, runs after the GPU array whatever its outcome). Collates every seed into
# results.csv and writes SUMMARY.md, listing any disease/seed that failed, timed out or
# was skipped. Seed-ensembled rank = rank of the mean raw score over seeds (adopted method).
import json
import os
import pickle
import subprocess

import numpy as np
import pandas as pd

from config import TAG, ORDER, RESOLVED, RESULTS_DIR, SEEDS, TRY_DIR, UNRELIABLE_COS

R = json.load(open(RESOLVED))
B_JOB = os.environ.get('B_JOB')


def array_states():
    if not B_JOB:
        return {}
    out = subprocess.run(['sacct', '-j', B_JOB, '-X', '-n', '-P', '-o', 'JobID,State,Elapsed'],
                         capture_output=True, text=True).stdout
    st = {}
    for line in out.strip().splitlines():
        jid, state, el = line.split('|')
        if '_' in jid and jid.split('_')[1].isdigit():
            st[int(jid.split('_')[1])] = f'{state} ({el})'
    return st


def rank_of(scores, drug):
    ids = list(scores)
    v = np.array([scores[k] for k in ids])
    order = np.argsort(-v, kind='stable')
    pos = {ids[j]: i + 1 for i, j in enumerate(order)}
    return pos.get(drug), len(ids)


def load(name, seed, q):
    p = os.path.join(RESULTS_DIR, name, f'seed_{seed}', f'eval_{int(float(q))}.pkl')
    if not os.path.exists(p):
        return None
    o = pickle.load(open(p, 'rb'))
    (preds,) = o['prediction'].values()   # keyed by raw PrimeKG id string; one disease per call
    return preds


states = array_states()
rows, ens_rows, notes = [], [], []
for i, name in enumerate(ORDER):
    info = R[name]
    st = states.get(i, 'unknown (no sacct record)')
    if not info['ok']:
        notes.append(f'- **{name}** ({info["label"]}): not run. Not evaluable or failed audit; see resolution_report.md. Array task: {st}')
        continue
    for q, ev in info['eval'].items():
        pr = info['proto'][q]
        keys = '; '.join(f'{k["raw_id"]}({k["cos"]})' for k in pr['keys'])
        hit = any(k['ref_hits'] for k in pr['keys'])
        reliable = pr['best_cos'] >= UNRELIABLE_COS
        per_seed = {}
        for s in SEEDS:
            preds = load(name, s, q)
            if preds is None:
                notes.append(f'- **{name}** @ {ev["name"]} seed {s}: NO OUTPUT. Array task {i}: {st}')
                continue
            per_seed[s] = preds
            bj = os.path.join(RESULTS_DIR, name, f'seed_{s}', 'blind.json')
            blind = json.load(open(bj))['blind_check_passed'] if os.path.exists(bj) else info['blind_check_passed']
            for db, dn in info['evaluable_ref'].items():
                r, n = rank_of(preds, db)
                rows.append(dict(disease=name, eval_node=ev['name'], internal_idx=float(q), seed=s,
                                 ref_drug=dn, ref_drug_db_id=db, rank=r, percentile=round(r / n, 4) if r else None,
                                 proto_hit=hit, proto_best_cos=pr['best_cos'], reliable=reliable,
                                 proto_keys=keys, n_holdout_nodes=len(info['holdout']),
                                 blind_check_passed=blind, score_zero=preds.get(db) == 0))
        if len(per_seed) == len(SEEDS):
            ens = {k: float(np.mean([p[k] for p in per_seed.values()])) for k in per_seed[SEEDS[0]]}
            for db, dn in info['ref'].items():
                r, n = rank_of(ens, db)
                zero = all(p.get(db) == 0 for p in per_seed.values())
                ens_rows.append(dict(disease=name, eval_node=ev['name'], ref_drug=dn,
                                     answer_edge=db in info['evaluable_ref'], ens_rank=r, n_drugs=n,
                                     best_cos=pr['best_cos'], reliable=reliable, proto_hit=hit, zero=zero))
        elif per_seed:
            notes.append(f'- **{name}** @ {ev["name"]}: only seeds {sorted(per_seed)} finished -- no ensemble rank reported')

df = pd.DataFrame(rows)
df.to_csv(os.path.join(TRY_DIR, f'results{TAG}.csv'), index=False)
E = pd.DataFrame(ens_rows)
E.to_csv(os.path.join(TRY_DIR, f'results_ensemble{TAG}.csv'), index=False)

L = ['# try24 SUMMARY (auto-generated by collate.py)\n',
     'Rank of the reference drug out of all drugs (lower = better), mean raw score over seeds 1-3, then ranked.',
     f'UNRELIABLE = best lookalike similarity < {UNRELIABLE_COS}: the lookalikes are arbitrary, so the rank is not reported (try20).\n',
     '| disease | scored node | drug | answer edge | ensemble rank | percentile | best lookalike cos | lookalike carries drug |',
     '|---|---|---|---|---|---|---|---|']
for e in ens_rows:
    if e['zero']:
        rk, pc = 'unscoreable (exact 0.0, isolated drug)', '-'
    elif not e['answer_edge']:
        rk, pc = f'{e["ens_rank"]} (informational only)', f'{e["ens_rank"] / e["n_drugs"]:.3f}'
    elif not e['reliable']:
        rk, pc = 'UNRELIABLE', '-'
    else:
        rk, pc = f'{e["ens_rank"]} / {e["n_drugs"]}', f'{e["ens_rank"] / e["n_drugs"]:.3f}'
    L.append(f'| {e["disease"]} | {e["eval_node"]} | {e["ref_drug"]} | {e["answer_edge"]} | {rk} | {pc} | '
             f'{e["best_cos"]:.3f} | {e["proto_hit"]} |')
L.append('\n## Array task states\n')
for i, name in enumerate(ORDER):
    L.append(f'- task {i} {name}: {states.get(i, "unknown")}')
L.append('\n## Failed / skipped / incomplete\n')
L += notes or ['none']
open(os.path.join(TRY_DIR, f'SUMMARY{TAG}.md'), 'w').write('\n'.join(L) + '\n')
print('\n'.join(L))
